$pageTitle = 'Stock Movement Report';
$activeNav = 'reports';

// Filter Values
$filterItemId = (int)($_GET['item_id'] ?? 0);
$filterCategory = sanitize($_GET['category'] ?? '');
$filterType = strtoupper(sanitize($_GET['movement_type'] ?? 'ALL'));
$filterStartDate = sanitize($_GET['start_date'] ?? '');
$filterEndDate = sanitize($_GET['end_date'] ?? '');

// Retrieve Dropdown Options
$categories = getItemCategories($pdo);
$stmtItems = $pdo->query("SELECT id, item_code, item_name FROM items ORDER BY item_code ASC");
$itemsList = $stmtItems->fetchAll();

// Build Dynamic SQL Query for Report Records
$sql = "
    SELECT sm.id, sm.movement_date, sm.movement_type, sm.quantity, sm.reference_note,
           i.item_code, i.item_name, i.category, i.unit,
           u.full_name AS user_name
    FROM stock_movements sm
    JOIN items i ON sm.item_id = i.id
    JOIN users u ON sm.created_by = u.id
    WHERE 1=1
";
$params = [];

if ($filterItemId > 0) {
    $sql .= " AND sm.item_id = ?";
    $params[] = $filterItemId;
}

if (!empty($filterCategory)) {
    $sql .= " AND i.category = ?";
    $params[] = $filterCategory;
}

if ($filterType === 'IN' || $filterType === 'OUT') {
    $sql .= " AND sm.movement_type = ?";
    $params[] = $filterType;
}

if (!empty($filterStartDate)) {
    $sql .= " AND sm.movement_date >= ?";
    $params[] = $filterStartDate;
}

if (!empty($filterEndDate)) {
    $sql .= " AND sm.movement_date <= ?";
    $params[] = $filterEndDate;
}

$sql .= " ORDER BY sm.movement_date DESC, sm.id DESC";

$stmtReport = $pdo->prepare($sql);
$stmtReport->execute($params);
$reportRecords = $stmtReport->fetchAll();

// Calculate Dynamic Statistics based on Filtered Results
$totalStockIn = 0;
$totalStockOut = 0;

foreach ($reportRecords as $rec) {
    if ($rec['movement_type'] === 'IN') {
        $totalStockIn += (int)$rec['quantity'];
    } elseif ($rec['movement_type'] === 'OUT') {
        $totalStockOut += (int)$rec['quantity'];
    }
}

$netMovement = $totalStockIn - $totalStockOut;

